#!/usr/bin/env python3
"""Writes src/nimgrpc/wktdescriptors.nim: the FileDescriptorProto of each well-known type, as
protoc serializes it, for `nimgrpc/reflection` (a reflection client that asks for a file which
imports google/protobuf/timestamp.proto needs that file too).

Usage: tools/gen_wkt_descriptors.py [PROTOC]    (PROTOC defaults to protoc)
Note: the descriptors are those of the protoc that runs; use a recent one to keep newer fields
(for example `edition` in type.proto and api.proto)."""
import os
import subprocess
import sys
import tempfile

PROTOC = sys.argv[1] if len(sys.argv) > 1 else "protoc"
FILES = ["any", "api", "duration", "empty", "field_mask", "source_context", "struct",
         "timestamp", "type", "wrappers"]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "nimgrpc",
                   "wktdescriptors.nim")


def varint(buf, pos):
    shift = result = 0
    while True:
        b = buf[pos]
        pos += 1
        result |= (b & 0x7F) << shift
        if not b & 0x80:
            return result, pos
        shift += 7


with tempfile.TemporaryDirectory() as tmp:
    ds = os.path.join(tmp, "wkt.ds")
    subprocess.run([PROTOC, "--descriptor_set_out=" + ds, "--include_imports"] +
                   ["google/protobuf/%s.proto" % f for f in FILES], check=True)
    data = open(ds, "rb").read()

files = []                       # (name, bytes) of each FileDescriptorProto of the set
pos = 0
while pos < len(data):
    tag, pos = varint(data, pos)
    assert tag == (1 << 3 | 2), "a FileDescriptorSet holds only files"
    n, pos = varint(data, pos)
    raw = data[pos:pos + n]
    pos += n
    assert raw[0] == 0x0A        # the name is the first field
    ln, p = varint(raw, 1)
    files.append((raw[p:p + ln].decode(), raw))

lines = [
    "# Generated by tools/gen_wkt_descriptors.py. DO NOT EDIT.",
    "## The FileDescriptorProto of each well-known type, for `nimgrpc/reflection`.",
    "",
    "const wellKnownDescriptors*: array[%d, tuple[name, data: string]] = [" % len(files),
]
for name, raw in sorted(files):
    lines.append('  ("%s",' % name)
    chunks = [raw[i:i + 24] for i in range(0, len(raw), 24)]
    for i, c in enumerate(chunks):
        lines.append('    "' + "".join("\\x%02x" % b for b in c) + '"' + (" &" if i + 1 < len(chunks) else ""))
    lines.append("  ),")
lines.append("]")
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote %s: %d files" % (os.path.normpath(OUT), len(files)))
